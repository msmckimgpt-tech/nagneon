const {app,BrowserWindow,session}=require('electron');
const {createStudioSession}=require('../desktop/session.cjs');
const {resolve,join}=require('node:path');
const {pathToFileURL}=require('node:url');
const {mkdirSync,writeFileSync}=require('node:fs');
const assert=require('node:assert/strict');
const folder=resolve('artifacts/gpu-settings-ui-'+Date.now());mkdirSync(folder,{recursive:true});app.setPath('userData',join(folder,'profile'));
mkdirSync(join(folder,'data'));writeFileSync(join(folder,'data/onboarding.json'),JSON.stringify({version:1,status:'skipped',completedAt:Date.now()}));
let service,win;const checks=[];
setTimeout(()=>app.exit(2),60000).unref();
app.whenReady().then(async()=>{try{
 const {startServer}=await import(pathToFileURL(resolve('server/index.js')));
 service=await startServer({port:0,dataDir:join(folder,'data'),localSpeech:false});
 win=new BrowserWindow({width:1200,height:900,show:false,webPreferences:{backgroundThrottling:false,session:createStudioSession(session,service)}});
 await win.loadURL(service.url);
 const js=code=>win.webContents.executeJavaScript(code);
 const until=async fn=>{for(let i=0;i<100;i++){if(await fn())return;await new Promise(r=>setTimeout(r,100));}throw Error('UI timeout');};
 const click=label=>js(`Array.from(document.querySelectorAll('button')).find(b=>b.textContent.trim()===${JSON.stringify(label)}).click()`);
 await until(()=>js(`!!Array.from(document.querySelectorAll('button')).find(b=>b.textContent.trim()==='방송 설정')`));
 await click('방송 설정');await click('미디어·기록');
 const select=`Array.from(document.querySelectorAll('select')).find(s=>Array.from(s.options).some(o=>o.value==='gpu'))`;
 assert.equal(await js(`${select}.value`),'gpu');checks.push('GPU default rendered in Settings > Media');
 await js(`{const s=${select};Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(s,'cpu');s.dispatchEvent(new Event('change',{bubbles:true}));}`);
 await click('설정 저장');await until(()=>Promise.resolve(service.studio.settings.speechDevice==='cpu'));
 await win.reload();await until(()=>js(`!!Array.from(document.querySelectorAll('button')).find(b=>b.textContent.trim()==='방송 설정')`));
 await click('방송 설정');await click('미디어·기록');assert.equal(await js(`${select}.value`),'cpu');checks.push('CPU selection saves and survives page reload');
 writeFileSync(join(folder,'settings.png'),(await win.webContents.capturePage()).toPNG());
 await service.close();service=await startServer({port:0,dataDir:join(folder,'data'),localSpeech:false});assert.equal(service.studio.settings.speechDevice,'cpu');checks.push('CPU selection survives service restart');
 writeFileSync('artifacts/gpu-settings-ui.json',JSON.stringify({passed:true,checks,folder},null,2));
}catch(e){console.error(e);writeFileSync('artifacts/gpu-settings-ui-failure.json',JSON.stringify({error:e.message,checks}));process.exitCode=1;}finally{win?.destroy();await service?.close();app.exit(process.exitCode||0);}});
